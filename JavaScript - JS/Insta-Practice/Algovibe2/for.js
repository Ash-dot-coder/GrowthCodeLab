// for loop
// Note: With the "for loop", the declaration and initialization of the loop variable, condition checking, and increment/decrement of the loop variable take place on a single line.

// Increment
for (let i = 0; i <= 5; i++) {
    console.log(i);
}

// Decrement
for (let d = 5; d >= 0; d--) {
    console.log(d);
}